const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

// Execute the shared production button handler without sending any real request.
(async () => {
    const source = fs.readFileSync('resources/views/component/action_buttons.blade.php', 'utf8');
    const script = source.match(/<script>([\s\S]*?)<\/script>/)[1];
    const requests = [], toasts = [], confirmations = [];
    let reloads = 0, blocked = false;
    const window = { appConfirm: async message => { confirmations.push(message); return true; }, appToast: message => toasts.push(message), location: { reload: () => reloads++ } };
    const context = { window, console, document: { addEventListener() {}, querySelector: () => ({ getAttribute: () => 'qa-csrf' }) }, sessionStorage: { setItem() {} }, fetch: async (url, options) => {
        requests.push({ url, ...options });
        return { ok: !blocked, headers: { get: () => 'application/json' }, json: async () => blocked ? { success: false, message: 'Driver is in use' } : { route: '/driver' } };
    } };
    vm.runInNewContext(script, context);
    const button = { dataset: { deleteUrl: '/driver/5/delete', deleteMethod: 'POST', entityName: 'Driver' }, style: {} };
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[0].method, 'POST');
    assert.equal(requests[0].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(requests[0].url, '/driver/5/delete');
    assert.equal(reloads, 1);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 1);
    assert.deepEqual(toasts, ['Driver is in use']);
    assert.equal(button.style.pointerEvents, 'auto');
    blocked = false;
    button.dataset.deleteUrl = '/status/100/delete';
    button.dataset.entityName = 'Status';
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[2].url, '/status/100/delete');
    assert.equal(requests[2].method, 'POST');
    assert.equal(requests[2].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(reloads, 2);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 2);
    assert.equal(toasts.length, 2);
    blocked = false;
    button.dataset.deleteUrl = '/room_types/100/delete';
    button.dataset.deleteMessage = 'Permanently delete this room type? This cannot be undone.';
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[4].url, '/room_types/100/delete');
    assert.equal(requests[4].method, 'POST');
    assert.equal(requests[4].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(confirmations.at(-1), button.dataset.deleteMessage);
    assert.equal(reloads, 3);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 3);
    blocked = false;
    button.dataset.deleteUrl = '/rate/100/delete';
    delete button.dataset.deleteMessage;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[6].url, '/rate/100/delete');
    assert.equal(requests[6].method, 'POST');
    assert.equal(requests[6].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(reloads, 4);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 4);
    blocked = false;
    button.dataset.deleteUrl = '/currency_rate/100/delete';
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[8].url, '/currency_rate/100/delete');
    assert.equal(requests[8].method, 'POST');
    assert.equal(requests[8].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(reloads, 5);
    button.dataset.deleteUrl = '/currencies/100/delete';
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[9].url, '/currencies/100/delete');
    assert.equal(requests[9].method, 'POST');
    assert.equal(requests[9].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(reloads, 6);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 6);
    blocked = false;
    button.dataset.deleteUrl = '/criteria/100/delete';
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[11].url, '/criteria/100/delete');
    assert.equal(requests[11].method, 'POST');
    assert.equal(requests[11].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(reloads, 7);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 7);
    blocked = false;
    button.dataset.deleteUrl = '/comment/100/delete';
    button.dataset.deleteMessage = 'Archive this comment? Replies will be preserved.';
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[13].url, '/comment/100/delete');
    assert.equal(requests[13].method, 'POST');
    assert.equal(requests[13].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(confirmations.at(-1), button.dataset.deleteMessage);
    assert.equal(reloads, 8);
    button.dataset.deleteUrl = '/clients/100/delete';
    delete button.dataset.deleteMessage;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[14].url, '/clients/100/delete');
    assert.equal(requests[14].method, 'POST');
    assert.equal(requests[14].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(reloads, 9);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 9);
    blocked = false;
    button.dataset.deleteUrl = '/accounting/100/delete';
    button.dataset.deleteMessage = 'Archive this invoice? Its financial records will be preserved.';
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests[16].url, '/accounting/100/delete');
    assert.equal(requests[16].method, 'POST');
    assert.equal(requests[16].headers['X-CSRF-TOKEN'], 'qa-csrf');
    assert.equal(confirmations.at(-1), button.dataset.deleteMessage);
    assert.equal(reloads, 10);
    blocked = true;
    context.confirmDelete(button);
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(reloads, 10);
    console.log('PASS: all ten module delete/archive handlers use POST with CSRF; blocked deletes show errors; invoices explain record preservation.');
})().catch(error => { console.error(error); process.exitCode = 1; });
